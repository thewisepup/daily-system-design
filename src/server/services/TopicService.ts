import { complete } from "../llm/openRouterClient";
import { topicRepo } from "../db/repo/topicRepo";
import { subjectRepo } from "../db/repo/subjectRepo";
import { syllabusBatchPrompt } from "../llm/prompts.ts/syllabusPrompt";
import { TopicsResponseSchema } from "../llm/schemas/topics";
import type { Topic } from "../db/schema/topics";

interface GenerateTopicsResult {
  success: boolean;
  topicsCreated: number;
  totalBatches: number;
  duration: number;
}

export interface EnsureTopicExistsResult {
  topic: Topic;
  wasAutoGenerated: boolean;
}

class TopicService {
  /**
   * Ensures a topic exists for a given subject and sequence order.
   * If no topic exists at the specified sequence, generates a new batch of topics.
   *
   * @param subjectId - The subject ID to check/generate topics for
   * @param sequenceOrder - The sequence order that must have a topic
   * @param batchSize - Number of topics to generate if needed (default: 10)
   * @returns The topic at the requested sequence and whether it was auto-generated
   *
   * @throws {Error} When topic generation fails
   * @throws {Error} When topic still doesn't exist after generation
   */
  async ensureTopicExists(
    subjectId: number,
    sequenceOrder: number,
    batchSize = 10,
  ): Promise<EnsureTopicExistsResult> {
    const existingTopic = await topicRepo.findBySubjectIdAndSequence(
      subjectId,
      sequenceOrder,
    );

    if (existingTopic) {
      console.log(
        `[TopicService] Topic exists for subject ${subjectId} at sequence ${sequenceOrder}`,
      );
      return { topic: existingTopic, wasAutoGenerated: false };
    }

    console.log(
      `[TopicService] No topic found for subject ${subjectId} at sequence ${sequenceOrder}, auto-generating batch...`,
    );

    await this.generateTopics(subjectId, batchSize);

    const generatedTopic = await topicRepo.findBySubjectIdAndSequence(
      subjectId,
      sequenceOrder,
    );

    if (!generatedTopic) {
      throw new Error(
        `Failed to generate topic for subject ${subjectId} at sequence ${sequenceOrder}. ` +
          `Topic generation succeeded but topic at requested sequence was not created.`,
      );
    }

    console.log(
      `[TopicService] Successfully auto-generated topic "${generatedTopic.title}" at sequence ${sequenceOrder}`,
    );

    return { topic: generatedTopic, wasAutoGenerated: true };
  }

  /**
   * Generates a batch of topics for a subject using LLM and saves them to the database.
   *
   * @param subjectId - The subject ID to generate topics for
   * @param batchSize - Number of topics to generate (default: 10)
   * @returns Result containing success status, topics created count, and duration
   *
   * @throws {Error} When subject does not exist
   * @throws {Error} When AI returns no topics
   * @throws {Error} When database insert fails
   */
  async generateTopics(
    subjectId: number,
    batchSize = 10,
  ): Promise<GenerateTopicsResult> {
    const startTime = Date.now();

    try {
      const subject = await subjectRepo.findById(subjectId);
      if (!subject) {
        throw new Error(`Subject with ID ${subjectId} does not exist`);
      }

      const existingTitles = await topicRepo.getExistingTitles(subjectId);
      const highestSequenceOrder =
        await topicRepo.getHighestSequenceOrder(subjectId);
      const startSequenceOrder = highestSequenceOrder + 1;

      console.log(
        `[Generate Topics] Generating ${batchSize} topics starting from sequence order ${startSequenceOrder}`,
      );

      const syllabusStartTime = Date.now();
      const prompt = syllabusBatchPrompt(
        subject.name,
        startSequenceOrder,
        batchSize,
        existingTitles,
      );
      console.log("[Generate Topics] --Prompt: --");
      console.log(prompt);
      console.log("[Generate Topics] --End Prompt: --");

      const response = await complete({
        prompt,
        schema: TopicsResponseSchema,
        schemaName: "topics_response",
        model: "anthropic/claude-sonnet-4.5",
      });

      console.log("[Generate Topics] --AI Response: --");
      console.log(JSON.stringify(response, null, 2));
      console.log("[Generate Topics] --End AI Response: --");

      const syllabusDuration = Date.now() - syllabusStartTime;
      console.log(`Batch generation completed (${syllabusDuration}ms)`);

      if (!response.topics || response.topics.length === 0) {
        throw new Error("AI returned no topics");
      }

      if (response.topics.length !== batchSize) {
        console.warn(
          `Expected ${batchSize} topics, got ${response.topics.length}`,
        );
      }

      const topicsForDb = response.topics.map((topic) => ({
        title: topic.title,
        topicData: topic,
        subjectId,
        sequenceOrder: topic.sequenceOrder,
      }));

      console.log(
        `[Generate Topics]Saving ${topicsForDb.length} topics to database...`,
      );
      const createdTopics = await topicRepo.createMany(topicsForDb);

      if (!createdTopics || createdTopics.length === 0) {
        throw new Error("Failed to create topics in database");
      }

      const duration = Date.now() - startTime;
      console.log(
        `[Generate Topics] Done. Generated ${createdTopics.length} topics in ${duration}ms total`,
      );

      return {
        success: true,
        topicsCreated: createdTopics.length,
        totalBatches: 1,
        duration,
      };
    } catch (error) {
      const duration = Date.now() - startTime;
      console.error(`Failed after ${duration}ms:`, error);
      throw error;
    }
  }
}

export const topicService = new TopicService();
